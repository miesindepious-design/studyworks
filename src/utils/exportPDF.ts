/**
 * exportPDF.ts — Real PDF export using `pdf-lib`.
 *
 * Replaces the previous `window.print()` approach which relied on the
 * browser's "Print to PDF" dialog. That worked on desktop but not on
 * iOS Safari or mobile Chrome, and it didn't produce a real .pdf file —
 * the user had to choose "Save as PDF" themselves.
 *
 * The output is a proper downloadable .pdf with:
 *   - Cover page (title, date, item counts)
 *   - One section per category (notes / flashcards / contacts)
 *   - Page breaks between items
 *   - Word-wrapped text with proper margins
 *
 * For heavy layouts (hundreds of notes), this is more reliable than
 * HTML+print across browsers and is the same file the user would get
 * from the print dialog anyway.
 */

import { PDFDocument, StandardFonts, rgb, PDFPage, PDFFont } from 'pdf-lib';
import type { Note, Flashcard, Contact } from '../types';
import { toPlainText } from './text';

// ── Layout constants ──────────────────────────────────────────────────────────
const PAGE_W = 595.28;   // A4 width in points
const PAGE_H = 841.89;   // A4 height
const MARGIN = 50;
const CONTENT_W = PAGE_W - MARGIN * 2;
const LINE_H = 14;
const TITLE_SIZE = 22;
const H2_SIZE = 14;
const BODY_SIZE = 10;
const META_SIZE = 9;

const COL_INDIGO = rgb(0.388, 0.4, 0.945);     // var(--accent) ~ #6366f1
const COL_TEXT   = rgb(0.118, 0.161, 0.231);   // slate-800
const COL_MUTED  = rgb(0.392, 0.455, 0.545);   // slate-500
const COL_LINE   = rgb(0.890, 0.906, 0.941);   // slate-200
const COL_BG     = rgb(0.969, 0.976, 0.988);   // slate-100

// ── Public entry points ──────────────────────────────────────────────────────

export async function exportNotesToPDF(notes: Note[]): Promise<void> {
  const pdf = await PDFDocument.create();
  pdf.setTitle(`StudyWorks Notes — ${notes.length} items`);
  await renderLibraryPage(pdf, { notes, flashcards: [], contacts: [] });
  await downloadPdf(pdf, `studyworks-notes-${today()}.pdf`);
}

export async function exportFullLibraryToPDF(
  notes: Note[], flashcards: Flashcard[], contacts: Contact[]
): Promise<void> {
  const pdf = await PDFDocument.create();
  pdf.setTitle(`StudyWorks — Full library (${notes.length} notes, ${flashcards.length} cards, ${contacts.length} contacts)`);
  await renderLibraryPage(pdf, { notes, flashcards, contacts });
  await downloadPdf(pdf, `studyworks-library-${today()}.pdf`);
}

// ── Internals ────────────────────────────────────────────────────────────────

interface LibraryParams {
  notes: Note[];
  flashcards: Flashcard[];
  contacts: Contact[];
}

async function renderLibraryPage(pdf: PDFDocument, { notes, flashcards, contacts }: LibraryParams): Promise<void> {
  const font      = await pdf.embedFont(StandardFonts.Helvetica);
  const fontBold  = await pdf.embedFont(StandardFonts.HelveticaBold);

  // Cover page
  let page = pdf.addPage([PAGE_W, PAGE_H]);
  let y = PAGE_H - MARGIN;
  drawCenteredText(page, 'StudyWorks',  PAGE_W / 2, y, fontBold, TITLE_SIZE + 6, COL_INDIGO);
  y -= 30;
  drawCenteredText(page, 'Full library export', PAGE_W / 2, y, font, BODY_SIZE + 2, COL_MUTED);
  y -= 12;
  drawCenteredText(page, todayLong(), PAGE_W / 2, y, font, BODY_SIZE, COL_MUTED);
  y -= 40;
  drawCoverStat(page, '📝 Notes',      notes.length,      y, font, fontBold); y -= 28;
  drawCoverStat(page, '💡 Flashcards', flashcards.length, y, font, fontBold); y -= 28;
  drawCoverStat(page, '👥 Contacts',   contacts.length,  y, font, fontBold); y -= 40;
  drawWrappedText(page, 'Generated by StudyWorks — your private study library, ready to print or archive.',
    MARGIN, y, CONTENT_W, font, BODY_SIZE, COL_MUTED, 3);

  // Notes section
  if (notes.length) {
    page = startSection(pdf, 'Notes', fontBold);
    y = PAGE_H - MARGIN - 30;
    for (const n of notes) {
      ({ page, y } = ensureSpace(pdf, page, y, 60, font, fontBold, 'Notes'));
      y = drawNote(pdf, page, n, y, font, fontBold);
      y -= 14;
    }
  }

  // Flashcards section
  if (flashcards.length) {
    page = startSection(pdf, 'Flashcards', fontBold);
    y = PAGE_H - MARGIN - 30;
    for (const c of flashcards) {
      ({ page, y } = ensureSpace(pdf, page, y, 50, font, fontBold, 'Flashcards'));
      y = drawCard(pdf, page, c, y, font, fontBold);
      y -= 10;
    }
  }

  // Contacts section
  if (contacts.length) {
    page = startSection(pdf, 'People', fontBold);
    y = PAGE_H - MARGIN - 30;
    for (const c of contacts) {
      ({ page, y } = ensureSpace(pdf, page, y, 50, font, fontBold, 'People'));
      y = drawContact(pdf, page, c, y, font, fontBold);
      y -= 10;
    }
  }
}

// ── Drawing helpers ──────────────────────────────────────────────────────────

function drawCenteredText(page: PDFPage, text: string, x: number, y: number, font: PDFFont, size: number, color: ReturnType<typeof rgb>) {
  const w = font.widthOfTextAtSize(text, size);
  page.drawText(text, { x: x - w / 2, y, size, font, color });
}

function drawCoverStat(page: PDFPage, label: string, count: number, y: number, font: PDFFont, fontBold: PDFFont) {
  const total = `${label}: ${count}`;
  const w = font.widthOfTextAtSize(total, BODY_SIZE + 1);
  page.drawText(total, { x: (PAGE_W - w) / 2, y, size: BODY_SIZE + 1, font: fontBold, color: COL_TEXT });
}

function startSection(pdf: PDFDocument, title: string, fontBold: PDFFont): PDFPage {
  const page = pdf.addPage([PAGE_W, PAGE_H]);
  page.drawText(title, {
    x: MARGIN, y: PAGE_H - MARGIN,
    size: H2_SIZE + 2, font: fontBold, color: COL_INDIGO,
  });
  // Underline
  page.drawLine({
    start: { x: MARGIN, y: PAGE_H - MARGIN - 4 },
    end:   { x: MARGIN + 60, y: PAGE_H - MARGIN - 4 },
    thickness: 1.5, color: COL_INDIGO,
  });
  return page;
}

function drawNote(pdf: PDFDocument, page: PDFPage, n: Note, y: number, font: PDFFont, fontBold: PDFFont): number {
  // Card background
  const cardTop = y;
  // Title
  page.drawText(n.title || '(untitled)', { x: MARGIN, y, size: BODY_SIZE + 2, font: fontBold, color: COL_TEXT });
  y -= LINE_H;
  // Meta
  const meta: string[] = [];
  if (n.type && n.type !== 'note') meta.push(`type: ${n.type}`);
  if (n.folderId) meta.push(`folder: ${n.folderId.slice(0, 8)}`);
  meta.push(new Date(n.createdAt).toLocaleDateString());
  page.drawText(meta.join('  ·  '), { x: MARGIN, y, size: META_SIZE, font, color: COL_MUTED });
  y -= LINE_H;
  // Tags
  if (n.tags && n.tags.length) {
    page.drawText(n.tags.map(t => `#${t}`).join(' '), { x: MARGIN, y, size: META_SIZE, font, color: COL_INDIGO });
    y -= LINE_H;
  }
  // Summary box
  if (n.summary) {
    ({ y } = drawBox(pdf, page, MARGIN, y - 4, CONTENT_W, LINE_H * 2, () => {
      page.drawText('Summary', { x: MARGIN + 6, y: y - 10, size: META_SIZE, font: fontBold, color: COL_MUTED });
    }));
    y = drawWrappedText(page, n.summary, MARGIN + 6, y - 4, CONTENT_W - 12, font, BODY_SIZE, COL_TEXT, 5);
    y -= 6;
  }
  // Body
  const text = toPlainText(n.content || '').trim();
  if (text) {
    y = drawWrappedText(page, text, MARGIN, y - 4, CONTENT_W, font, BODY_SIZE, COL_TEXT, 30);
  }
  // Card border
  const cardH = cardTop - y + 6;
  page.drawRectangle({
    x: MARGIN - 4, y: y - 2,
    width: CONTENT_W + 8, height: cardH,
    borderColor: COL_LINE, borderWidth: 0.5,
    color: rgb(1, 1, 1), opacity: 0,
  });
  return y - 4;
}

function drawCard(_: PDFDocument, page: PDFPage, c: Flashcard, y: number, font: PDFFont, fontBold: PDFFont): number {
  page.drawText('Q: ' + c.question, { x: MARGIN, y, size: BODY_SIZE, font: fontBold, color: COL_TEXT });
  y -= LINE_H;
  const ans = `A: ${c.answer}`;
  y = drawWrappedText(page, ans, MARGIN, y, CONTENT_W, font, BODY_SIZE, COL_TEXT, 6);
  if (c.difficulty) {
    page.drawText(`Difficulty: ${c.difficulty}`, { x: MARGIN, y, size: META_SIZE, font, color: COL_MUTED });
    y -= LINE_H;
  }
  if (c.tags && c.tags.length) {
    page.drawText(c.tags.map(t => `#${t}`).join(' '), { x: MARGIN, y, size: META_SIZE, font, color: COL_INDIGO });
    y -= LINE_H;
  }
  return y;
}

function drawContact(_: PDFDocument, page: PDFPage, c: Contact, y: number, font: PDFFont, fontBold: PDFFont): number {
  page.drawText(c.name, { x: MARGIN, y, size: BODY_SIZE + 1, font: fontBold, color: COL_TEXT });
  page.drawText(c.role, { x: MARGIN + 200, y, size: BODY_SIZE, font, color: COL_MUTED });
  y -= LINE_H;
  const lines: string[] = [];
  if (c.email) lines.push(`✉  ${c.email}`);
  if (c.phone) lines.push(`☎  ${c.phone}`);
  for (const line of lines) {
    page.drawText(line, { x: MARGIN, y, size: BODY_SIZE, font, color: COL_TEXT });
    y -= LINE_H;
  }
  if (c.notes) y = drawWrappedText(page, c.notes, MARGIN, y, CONTENT_W, font, BODY_SIZE, COL_TEXT, 5);
  if (c.tags && c.tags.length) {
    page.drawText(c.tags.map(t => `#${t}`).join(' '), { x: MARGIN, y, size: META_SIZE, font, color: COL_INDIGO });
    y -= LINE_H;
  }
  return y;
}

/** Word-wrap text and draw it. Returns the new y position. `maxLines` caps
 *  the height and appends '…' if the text was truncated. */
function drawWrappedText(
  page: PDFPage, text: string, x: number, y: number, maxWidth: number,
  font: PDFFont, size: number, color: ReturnType<typeof rgb>, maxLines: number
): number {
  const words  = text.split(/\s+/).filter(Boolean);
  const lines: string[] = [];
  let current = '';
  for (const w of words) {
    const candidate = current ? current + ' ' + w : w;
    if (font.widthOfTextAtSize(candidate, size) > maxWidth) {
      if (current) lines.push(current);
      current = w;
      if (lines.length >= maxLines - 1) break;
    } else {
      current = candidate;
    }
  }
  if (current && lines.length < maxLines) lines.push(current);
  const truncated = lines.length >= maxLines && words.length > lines.join(' ').split(/\s+/).length;
  const finalLines = lines.slice(0, maxLines);
  for (const line of finalLines) {
    page.drawText(line, { x, y, size, font, color });
    y -= LINE_H;
  }
  if (truncated) {
    page.drawText('…', { x, y, size, font, color: COL_MUTED });
    y -= LINE_H;
  }
  return y;
}

function drawBox(
  _pdf: PDFDocument, page: PDFPage,
  x: number, y: number, w: number, _h: number,
  drawContent: () => void
): { y: number } {
  page.drawRectangle({
    x, y: y - 14, width: w, height: 14,
    color: COL_BG, borderColor: COL_LINE, borderWidth: 0.5,
  });
  drawContent();
  return { y: y - 14 };
}

/** Make sure we have at least `needed` vertical points on the current page;
 *  if not, add a new page and start a new section. Returns the (possibly
 *  new) page and the new y. */
function ensureSpace(
  pdf: PDFDocument, page: PDFPage, y: number, needed: number,
  _font: PDFFont, fontBold: PDFFont, sectionTitle: string
): { page: PDFPage; y: number } {
  if (y - needed > MARGIN) return { page, y };
  return { page: startSection(pdf, `${sectionTitle} (cont.)`, fontBold), y: PAGE_H - MARGIN - 30 };
}

async function downloadPdf(pdf: PDFDocument, filename: string): Promise<void> {
  const bytes = await pdf.save();
  const blob  = new Blob([bytes], { type: 'application/pdf' });
  const url   = URL.createObjectURL(blob);
  const a     = document.createElement('a');
  a.href = url;
  a.download = filename;
  a.click();
  // Defer revoke so the browser can start the download.
  setTimeout(() => URL.revokeObjectURL(url), 1000);
}

function today(): string {
  return new Date().toISOString().split('T')[0];
}
function todayLong(): string {
  return new Date().toLocaleDateString(undefined, { year: 'numeric', month: 'long', day: 'numeric' });
}
